import { describe, expect, it } from "vitest";
import {
  CREW_ADVANCE_TEXT,
  CREW_ADVANCEMENT_ATTRIBUTION,
  CREW_ADVANCEMENT_SRD_URL,
  CREW_XP_CATEGORIES,
  CREW_XP_INTRO,
  CREW_XP_MAX_NOTE,
  CREW_PROFITS_TEXT,
} from "./crew-advancement.js";

describe("crew advancement SRD transcription (CREW-XP-INFO-01)", () => {
  it("links to the SRD crew advancement section and attributes CC-BY", () => {
    expect(CREW_ADVANCEMENT_SRD_URL).toBe("https://bladesinthedark.com/advancement#crew-advancement");
    expect(CREW_ADVANCEMENT_ATTRIBUTION).toContain("Blades in the Dark SRD (CC-BY)");
  });

  it("transcribes the SRD crew XP rule faithfully", () => {
    expect(CREW_XP_INTRO).toBe(
      "At the end of the session, review the crew XP triggers and mark 1 crew XP for each item that occurred during the session. If an item occurred multiple times or in a major way, mark 2 crew XP for it.",
    );
  });

  it("states that each category can yield up to 2 XP, not just 1", () => {
    expect(CREW_XP_MAX_NOTE).toContain("up to 2 XP");
    expect(CREW_XP_MAX_NOTE).toContain("2 if it occurred multiple times or in a major way");
  });

  it("lists the four SRD crew XP trigger categories in SRD order", () => {
    expect(CREW_XP_CATEGORIES.map((c) => c.title)).toEqual([
      "Your crew-specific xp trigger",
      "Contend with challenges above your current station.",
      "Bolster your crew’s reputation or develop a new one.",
      "Express the goals, drives, inner conflict, or essential nature of the crew.",
    ]);
    expect(CREW_XP_CATEGORIES[1]!.text).toBe("If you tangled with higher Tiers or more dangerous opposition, mark xp for this.");
  });

  it("transcribes the advance and profits rules", () => {
    expect(CREW_ADVANCE_TEXT).toBe(
      "When you fill your crew advancement tracker, clear the marks and take a new special ability or mark two crew upgrade boxes.",
    );
    expect(CREW_PROFITS_TEXT).toBe(
      "Every time the crew advances, each PC gets stash equal to the crew Tier+2, to represent profits generated by the crew as they’ve been operating.",
    );
  });
});
